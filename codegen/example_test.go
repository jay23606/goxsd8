package codegen_test

import (
	"fmt"
	"log"
	"os"
	"path/filepath"

	"github.com/kud360/goxsd8/codegen"
	"github.com/kud360/goxsd8/parser"
)

// ExampleGenerate parses a schema, generates package order from it into a
// temporary directory, a Go module's root, and prints the file Generate
// writes there.
func ExampleGenerate() {
	s, err := parser.Parse("testdata/example.xsd")
	if err != nil {
		log.Fatal(err)
	}
	root, err := os.MkdirTemp("", "codegen-example")
	if err != nil {
		log.Fatal(err)
	}
	defer func() {
		if err := os.RemoveAll(root); err != nil {
			log.Fatal(err)
		}
	}()
	// Each Dir lies in a Go module, which gives the package its import path.
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/app\n"), 0o644); err != nil {
		log.Fatal(err)
	}
	dir := filepath.Join(root, "gen", "order")

	if errs := codegen.Generate([]codegen.Target{{Schema: s, Dir: dir, Package: "order"}}); errs != nil {
		log.Fatal(errs)
	}

	src, err := os.ReadFile(filepath.Join(dir, "xsd_gen.go"))
	if err != nil {
		log.Fatal(err)
	}
	fmt.Print(string(src))
	// Output:
	// // Code generated by github.com/kud360/goxsd8/codegen. DO NOT EDIT.
	//
	// package order
	//
	// // Order is generated from element {urn:example}order declared at testdata/example.xsd:4:3.
	// type Order struct {
	// 	Item    []string
	// 	Note    *string
	// 	Payment Payment
	// 	Id      string
	// }
	//
	// // Payment is generated from element payment declared at testdata/example.xsd:9:9.
	// type Payment interface {
	// 	isPayment()
	// }
	//
	// // PaymentCard is generated from element card declared at testdata/example.xsd:12:15.
	// type PaymentCard struct {
	// 	Card string
	// }
	//
	// func (PaymentCard) isPayment() {}
}
