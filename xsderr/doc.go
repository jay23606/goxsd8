// Package xsderr is the error currency of the module: structured errors
// that carry a spec rule ID and a source location.
//
// # Using xsderr
//
// A caller holding an error from this module reaches its structured part
// with errors.As to an *xsderr.Error, which yields the Rule, the Loc and the
// Msg together; RuleOf and LocOf read the Rule or the Loc alone. An *Error
// holds no clause apart from Msg. By convention, not by check, Rule carries
// no part number — never the rule-plus-part-number name Appendix B
// recommends for reports — because one charge may cite several clauses, or a
// clause of another rule; by the same convention Msg names the clause a
// charge makes beside its Rule. Switch on Rule, and read a clause as prose.
// Error's doc says how a caller tells an *Error that is a validity verdict
// from one that is a fault.
//
// # Design
//
// It is a pure leaf — stdlib imports only. Every schema- or
// instance-validity violation the spec CATALOGS is an *Error carrying that
// catalog's rule ID (STYLE E2), and the one validity class the spec catalogs
// nowhere, below, is a plain error.
//
// # The s4s-grammar class
//
// A schema document that is simply not valid against the schema for schema
// documents — a prohibited or missing attribute, an unprefixed one the
// element's grammar declares nowhere, a child its content model does not
// admit, one repeated past its maxOccurs, one out of order —
// violates §2.4 clause 1 (sd-valid, xmlschema11-1.md:615). That clause is
// anchored but uncataloged: it is absent from Appendix B's three tables
// (B.1 cvc-*, B.3 src-*, B.4 cos-*), which are the spec's own exhaustive
// lists of citable codes, and §5.1's restatement of it (:4296) carries no
// anchor at all. No src-* covers the grammar either, by construction:
// §2.3's gloss-src (:607) defines Schema Representation Constraints as
// constraints "beyond those which are expressed in" that grammar, and every
// src-* with sub-clauses opens "In addition to the conditions imposed ...
// by the schema for schema documents" (src-ct, :1946; src-ta, :3218).
//
// So a rejection in this class carries no Rule and is not an *Error at all.
// It is a plain error whose message names the offending item, its location
// and the Appendix A production it violates — parser's rejectProhibitedAttrs
// and checkS4SChildOrder are the shape to copy. Do not charge it sd-valid,
// which is not a catalog ID and would read as one in the Rule position, and
// do not borrow the nearest src-*, which states a different constraint
// (#966). Nor does the class get a sentinel Rule of its own: it is a real
// validity verdict the spec declines to catalog, not a non-validity fault,
// and a Rule minted for it would be read as a citation of a rule the spec
// does not state.
//
// # The rule catalog
//
// catalog.go is generated by `go tool rulecat` from docs/specs/md: every
// rule ID that appears in the local specs, as the ruleCatalog lookup set.
// IsValidRule(Rule) bool is hand-written in error.go (not generated) so it
// can admit the non-spec sentinels alongside the generated catalog without
// regeneration clobbering those exemptions. Membership is exact — no
// clause-suffix leniency; see IsValidRule. Rule is a bare string type, so
// nothing in the Go type system stops an arbitrary one; the guarantee is
// enforced by test instead. rulecatalog_enforcement_test.go scans the whole
// module for two things: every constant declared with type Rule anywhere in the
// module must satisfy IsValidRule, and in non-test code no string literal may
// sit in one of four syntactic Rule positions — the first argument of New or
// Wrap, the Rule field of an Error composite literal, a Rule-typed result of a
// return statement, or the operand of a Rule(...) conversion. The return
// position alone admits "", the zero Rule; it is a violation in the other
// three. So a rule the spec doesn't define is caught wherever it is written as
// a Rule constant or as a literal in those four positions. That is a syntactic
// floor, not a dataflow proof: a Rule that reaches New/Wrap through a variable
// or another expression is not scanned, and the test's header comment names the
// residual holes it deliberately leaves open. The generate directive lives in
// gen.go.
